const dateTime = new Intl.DateTimeFormat('zh-CN', {
  timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit',
  hour: '2-digit', minute: '2-digit', hour12: false,
})
const dateTimeSeconds = new Intl.DateTimeFormat('zh-CN', {
  timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit',
  hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false,
})

export const formatDateTime = (value: string | number | Date) => dateTime.format(new Date(value))
export const formatDateTimeSeconds = (value: string | number | Date) => dateTimeSeconds.format(new Date(value))
